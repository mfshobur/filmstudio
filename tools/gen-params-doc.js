#!/usr/bin/env node
'use strict';
// Writes docs/agent-guide/18-params.md from the registry and the QA samples, so the doc can't drift from the code.
const fs = require('fs'), path = require('path');
const { STYLES } = require('../src/registry'), { sampleParams, SAMPLE_CHARACTERS } = require('../src/samples');
function render() {
  let o = '# 18 Shot params, with a working example for every variant\n\nGenerated by `tools/gen-params-doc.js` from the same samples the QA run draws, so every example here is known to draw. A shot is `[startBar, endBar, style, variant, params]`; the fifth item is only needed where the table says **required**. Copy an example and change the words.\n\n';
  for (const [k, v] of Object.entries(STYLES)) {
    const ex = v.variants.map(x => [x, sampleParams(k, x)]).filter(p => p[1] != null);
    o += '## `' + k + '`' + (v.params ? ' (params required)' : ex.length ? ' (params optional)' : ' (no params)') + '\nvariants: ' + v.variants.map(x => '`' + x + '`').join(', ') + '\n\n';
    if (ex.length) { o += '```json\n' + ex.map(([x, p]) => '[1, 3, "' + k + '", "' + x + '", ' + JSON.stringify(p) + ']').join('\n') + '\n```\n\n'; }
  }
  o += '## Characters (for `stage`)\nDefined in `spec.characters`. Example:\n\n```json\n' + JSON.stringify(SAMPLE_CHARACTERS, null, 1) + '\n```\n';
  return o;
}
if (require.main === module) { fs.writeFileSync(path.join(__dirname, '..', 'docs', 'agent-guide', '18-params.md'), render()); console.log('written'); }
module.exports = { render };
